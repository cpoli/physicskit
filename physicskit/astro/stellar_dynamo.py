r"""Stellar convection and the alpha-omega mean-field magnetic dynamo.

The Sun's large-scale magnetic field -- the one that reverses polarity
every ~11 years and paints the "butterfly diagram" of sunspots migrating
from mid-latitudes toward the equator -- is not a fossil field left over
from formation. It is continuously regenerated by the interplay of two
processes going on simultaneously in the convection zone: small-scale,
helical turbulent convection (the "alpha effect", parametrizing the net
effect of many individually chaotic convective eddies twisted by the
Sun's rotation and stratification) and the large-scale rotational shear
between the Sun's differentially rotating layers (the "Omega effect",
which stretches a poloidal field into a much stronger toroidal one).
Together these sustain the field against Ohmic decay -- this is the
alpha-omega dynamo mechanism first proposed by Parker (1955), and it is
the standard textbook explanation for the solar cycle.

A crucial and easy-to-miss subtlety (Zeldovich's antidynamo theorem) is
that a strictly two-dimensional, fully resolved magnetic field confined
to a plane *cannot* be sustained by 2D fluid motion alone -- genuine
dynamo action is an intrinsically three-dimensional effect, arising from
the helical (non-mirror-symmetric) twisting that only a 3D, rotating,
stratified flow can produce. This module therefore does not attempt to
build one dynamically self-consistent 2D "dynamo simulation" (which
would either not be a real dynamo, or would silently smuggle in 3D
physics through the back door). Instead, exactly as the textbook
treatment splits the problem, it implements two separate,
self-contained pieces:

- A resolved 2D Boussinesq convection simulation
  (:func:`simulate_stellar_convection`) showing the turbulent
  convective rolls and plumes whose unresolved, helical, three-dimensional
  fine structure is -- in the real Sun -- the physical origin of the
  alpha effect. This piece is a qualitative picture of the turbulence,
  not a dynamo; by Zeldovich's theorem it could never sustain a resolved
  2D field, and it is not asked to.
- The linearized 1D alpha-omega **mean-field** dynamo equations
  (:func:`simulate_alpha_omega_dynamo`), in which the alpha effect and
  the rotational shear enter as prescribed coefficients rather than
  being derived from the convection simulation above. This piece *does*
  robustly sustain and grow a large-scale field, and reproduces the
  real solar dynamo's most famous piece of phenomenology: a migrating
  dynamo wave, whose space-time diagram is the butterfly diagram.

The two pieces are deliberately not coupled to each other; each is
correct and complete on its own terms.

Part 1: 2D convective rolls
----------------------------

A standard doubly periodic, pseudo-spectral Boussinesq system for
vorticity :math:`\omega`, streamfunction :math:`\psi`, and temperature
perturbation :math:`T'` about an unstably stratified periodic background
:math:`T_{eq}(y) = -\beta\cos(2\pi y/L_y)`:

.. math::

    \partial_t \omega + \mathbf{u}\cdot\nabla\omega
        = \nu\nabla^2\omega + g\alpha_{th}\,\partial_x T' \\
    \partial_t T' + \mathbf{u}\cdot\nabla T'
        = \kappa\nabla^2 T' - u_y\,\frac{dT_{eq}}{dy}
          + \frac{T_{eq}(y) - T'}{\tau_{relax}} \\
    \nabla^2\psi = -\omega, \qquad \mathbf{u} = (\partial_y\psi, -\partial_x\psi)

The Newtonian-cooling term :math:`(T_{eq}-T')/\tau_{relax}` (together
with the advection of the background gradient, :math:`-u_y\,dT_{eq}/dy`)
is the standard trick for sustaining an unstable stratification in a
periodic box with no physical walls -- without it, convection would mix
the background profile flat and decay back to a quiescent state.

Part 2: The alpha-omega mean-field dynamo
-------------------------------------------

A linearized 1D reduction (Parker 1955; standard in mean-field dynamo
theory) for the poloidal-flux proxy :math:`A(x,t)` and toroidal field
:math:`B(x,t)`, periodic in :math:`x` (a local-Cartesian stand-in for
stellar latitude or radius):

.. math::

    \partial_t A = \alpha B + \eta\,\partial_x^2 A \\
    \partial_t B = G\,\partial_x A + \eta\,\partial_x^2 B

with constant alpha-effect coefficient :math:`\alpha`, shear rate
(Omega effect) :math:`G`, and magnetic diffusivity :math:`\eta`.
Substituting a plane-wave mode :math:`(A,B)\propto e^{ikx-i\omega_f t+\sigma t}`
turns this linear system into the 2x2 eigenvalue problem

.. math::

    \begin{pmatrix}\sigma-i\omega_f+\eta k^2 & -\alpha \\ -iGk & \sigma-i\omega_f+\eta k^2\end{pmatrix}
    \begin{pmatrix}A\\B\end{pmatrix} = 0,

whose characteristic equation, with :math:`s=\sigma-i\omega_f+\eta k^2`,
is :math:`s^2 = i\alpha G k`. Since :math:`i\alpha Gk` is purely
imaginary, its principal square root always has real and imaginary parts
of equal magnitude, :math:`\sqrt{|\alpha Gk|/2}` -- giving the closed-form
growth rate and wave frequency implemented in
:func:`alpha_omega_growth_rate` and :func:`alpha_omega_wave_frequency`,
and checked against the full simulation in this module's test suite.
Because the system is linear, each Fourier mode's amplitude can be
advanced *exactly* (no time-discretization error at all) via the 2x2
matrix exponential of its own coefficient matrix -- see
:func:`simulate_alpha_omega_dynamo`.
"""

