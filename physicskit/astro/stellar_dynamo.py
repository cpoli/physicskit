def _spectral_grid_2d(nx: int, ny: int, Lx: float, Ly: float):
    """Build the doubly periodic real-space and wavenumber grids for Part 1.

    Fields are laid out with shape ``(ny, nx)`` -- rows indexed by ``y``,
    columns by ``x`` -- the usual image-like convention (matches
    ``imshow``'s default axes and this module's documented snapshot
    shape). Self-contained (not imported from :mod:`physicskit.fluids`),
    per this package's no-cross-subpackage-imports convention, but built
    the same way as :func:`physicskit.fluids.core.grid.spectral_grid`:
    ``np.fft.fftfreq``-based wavenumbers, and the ``k=0`` mode of ``K2``
    set to 1 so the Poisson solve is safe to divide by.
    """
    x = np.linspace(0.0, Lx, nx, endpoint=False)
    y = np.linspace(0.0, Ly, ny, endpoint=False)
    X, Y = np.meshgrid(x, y, indexing="xy")
    kx = 2.0 * np.pi * np.fft.fftfreq(nx, d=Lx / nx)
    ky = 2.0 * np.pi * np.fft.fftfreq(ny, d=Ly / ny)
    KX, KY = np.meshgrid(kx, ky, indexing="xy")
    K2 = KX**2 + KY**2
    K2 = K2.copy()
    K2[0, 0] = 1.0
    return X, Y, KX, KY, K2


def _poisson_solve_streamfunction(omega: NDArray[np.float64], K2: NDArray[np.float64]) -> NDArray[np.float64]:
    """Solve :math:`\\nabla^2\\psi=-\\omega` for the streamfunction via FFT (see :func:`_spectral_grid_2d`)."""
    omega_hat = np.fft.fft2(omega)
    psi_hat = omega_hat / K2
    psi_hat[0, 0] = 0.0
    return np.real(np.fft.ifft2(psi_hat))


def _velocity_from_streamfunction(psi: NDArray[np.float64], KX: NDArray[np.float64], KY: NDArray[np.float64]):
    """Recover :math:`\\mathbf{u}=(\\partial_y\\psi,-\\partial_x\\psi)` from the streamfunction spectrally."""
    psi_hat = np.fft.fft2(psi)
    u = np.real(np.fft.ifft2(1j * KY * psi_hat))
    v = np.real(np.fft.ifft2(-1j * KX * psi_hat))
    return u, v


def convective_roll_rhs(
    omega: NDArray[np.float64],
    T: NDArray[np.float64],
    Y: NDArray[np.float64],
    KX: NDArray[np.float64],
    KY: NDArray[np.float64],
    K2: NDArray[np.float64],
    nu: float,
    kappa: float,
    g_alpha: float,
    beta: float,
    Ly: float,
    tau_relax: float,
):
    """Right-hand side of the 2D Boussinesq convective-roll system, evaluated pseudo-spectrally.

    Mirrors the structure of the Rayleigh-Taylor Boussinesq right-hand
    side used elsewhere in this codebase for a buoyancy-vorticity system
    (vorticity forced by the buoyancy field's :math:`x`-derivative,
    :math:`g\\,\\partial_x b`, since gravity and the background
    stratification both point along :math:`y`), plus the Newtonian-cooling
    forcing that sustains the unstable background profile
    :math:`T_{eq}(y)=-\\beta\\cos(2\\pi y/L_y)` against being mixed away by
    the convection it drives (see the module docstring).

    Parameters
    ----------
    omega, T : ndarray of float, shape (ny, nx)
        Vorticity and temperature-perturbation fields.
    Y : ndarray of float, shape (ny, nx)
        The ``y`` coordinate grid, from :func:`_spectral_grid_2d`, used to
        evaluate the background profile :math:`T_{eq}(y)` and its
        gradient pointwise.
    KX, KY, K2 : ndarray of float, shape (ny, nx)
        Wavenumber grids from :func:`_spectral_grid_2d`.
    nu : float
        Kinematic viscosity (vorticity diffusivity).
    kappa : float
        Thermal diffusivity.
    g_alpha : float
        Combined buoyancy coefficient :math:`g\\,\\alpha_{th}`.
    beta : float
        Amplitude of the background stratification :math:`T_{eq}(y)`.
    Ly : float
        Domain size along :math:`y` (the period of :math:`T_{eq}`).
    tau_relax : float
        Newtonian-cooling relaxation time back to :math:`T_{eq}(y)`.

    Returns
    -------
    domega_dt, dT_dt : ndarray of float, shape (ny, nx)
        Time derivatives of vorticity and temperature perturbation.
    """
    psi = _poisson_solve_streamfunction(omega, K2)
    u, v = _velocity_from_streamfunction(psi, KX, KY)

    omega_hat = np.fft.fft2(omega)
    domega_dx = np.real(np.fft.ifft2(1j * KX * omega_hat))
    domega_dy = np.real(np.fft.ifft2(1j * KY * omega_hat))
    diffusion_omega = np.real(np.fft.ifft2(-nu * K2 * omega_hat))

    T_hat = np.fft.fft2(T)
    dT_dx = np.real(np.fft.ifft2(1j * KX * T_hat))
    dT_dy = np.real(np.fft.ifft2(1j * KY * T_hat))
    diffusion_T = np.real(np.fft.ifft2(-kappa * K2 * T_hat))

    Teq = -beta * np.cos(2.0 * np.pi * Y / Ly)
    dTeq_dy = beta * (2.0 * np.pi / Ly) * np.sin(2.0 * np.pi * Y / Ly)

    domega_dt = -(u * domega_dx + v * domega_dy) + diffusion_omega + g_alpha * dT_dx
    dT_dt = -(u * dT_dx + v * dT_dy) + diffusion_T - v * dTeq_dy + (Teq - T) / tau_relax
    return domega_dt, dT_dt


def simulate_stellar_convection(
    nx: int,
    ny: int,
    Lx: float,
    Ly: float,
    nu: float = 0.08,
    kappa: float = 0.08,
    g_alpha: float = 2.0,
    beta: float = 1.0,
    tau_relax: float = 0.5,
    dt: float = 0.005,
    n_steps: int = 5000,
    save_every: int = 50,
    seed: int | None = None,
):
    """Time-step 2D Boussinesq convective rolls with pseudo-spectral RK4.

    Starts from a small random vorticity and temperature perturbation
    (root-mean-square amplitude ``1e-3``) and integrates
    :func:`convective_roll_rhs` with classical 4th-order Runge-Kutta,
    exactly the scheme used for the Boussinesq Rayleigh-Taylor system
    elsewhere in this codebase. The default parameters were tuned (see
    this module's test suite) so that the periodic background
    stratification :math:`T_{eq}(y)=-\\beta\\cos(2\\pi y/L_y)`, sustained
    against mixing by the ``tau_relax`` Newtonian-cooling forcing, robustly
    grows the seed noise into sustained convective rolls -- kinetic energy
    measurably larger at the end of the run than at the start -- without
    blowing up.

    Parameters
    ----------
    nx, ny : int
        Number of grid points along ``x`` and ``y``.
    Lx, Ly : float
        Physical domain size along ``x`` and ``y``.
    nu : float, default 0.08
        Kinematic viscosity.
    kappa : float, default 0.08
        Thermal diffusivity.
    g_alpha : float, default 2.0
        Combined buoyancy coefficient :math:`g\\,\\alpha_{th}`.
    beta : float, default 1.0
        Amplitude of the background stratification.
    tau_relax : float, default 0.5
        Newtonian-cooling relaxation time.
    dt : float, default 0.005
        Time step.
    n_steps : int, default 5000
        Total number of RK4 steps.
    save_every : int, default 50
        Save a snapshot every this many steps.
    seed : int, optional
        Random seed for the initial perturbation.

    Returns
    -------
    times : ndarray of float, shape (n_saved,)
    omega_snapshots : ndarray of float, shape (n_saved, ny, nx)
    T_snapshots : ndarray of float, shape (n_saved, ny, nx)

    See Also
    --------
    convective_roll_rhs : The right-hand side stepped here.
    kinetic_energy : Diagnostic used to confirm convection is sustained.

    Examples
    --------
    >>> times, omega_snaps, T_snaps = simulate_stellar_convection(
    ...     32, 32, 2 * np.pi, 2 * np.pi, n_steps=20, save_every=10, seed=0)
    >>> omega_snaps.shape[1:]
    (32, 32)
    >>> bool(np.all(np.isfinite(omega_snaps)))
    True
    """
    X, Y, KX, KY, K2 = _spectral_grid_2d(nx, ny, Lx, Ly)

    rng = np.random.default_rng(seed)
    omega = 1.0e-3 * rng.standard_normal((ny, nx))
    T = 1.0e-3 * rng.standard_normal((ny, nx))

    times = [0.0]
    omega_snapshots = [omega.copy()]
    T_snapshots = [T.copy()]

    t = 0.0
    for step in range(1, n_steps + 1):
        k1o, k1T = convective_roll_rhs(omega, T, Y, KX, KY, K2, nu, kappa, g_alpha, beta, Ly, tau_relax)
        k2o, k2T = convective_roll_rhs(omega + dt / 2 * k1o, T + dt / 2 * k1T, Y, KX, KY, K2, nu, kappa, g_alpha, beta, Ly, tau_relax)
        k3o, k3T = convective_roll_rhs(omega + dt / 2 * k2o, T + dt / 2 * k2T, Y, KX, KY, K2, nu, kappa, g_alpha, beta, Ly, tau_relax)
        k4o, k4T = convective_roll_rhs(omega + dt * k3o, T + dt * k3T, Y, KX, KY, K2, nu, kappa, g_alpha, beta, Ly, tau_relax)
        omega = omega + dt / 6 * (k1o + 2 * k2o + 2 * k3o + k4o)
        T = T + dt / 6 * (k1T + 2 * k2T + 2 * k3T + k4T)
        t += dt
        if step % save_every == 0:
            times.append(t)
            omega_snapshots.append(omega.copy())
            T_snapshots.append(T.copy())

    return np.array(times), np.array(omega_snapshots), np.array(T_snapshots)


def kinetic_energy(omega_snapshot: NDArray[np.float64], KX: NDArray[np.float64], KY: NDArray[np.float64], K2: NDArray[np.float64]) -> float:
    """Total kinetic energy of the flow implied by a vorticity snapshot.

    Recovers the streamfunction and velocity field from `omega_snapshot`
    via the same spectral Poisson solve used during time-stepping, then
    sums :math:`\\frac{1}{2}(u^2+v^2)` over the grid. Used as the
    diagnostic that convection in :func:`simulate_stellar_convection`
    actually spins up (grows) rather than decaying back to quiescence.

    Parameters
    ----------
    omega_snapshot : ndarray of float, shape (ny, nx)
        A single vorticity snapshot, e.g. one entry of the
        `omega_snapshots` array returned by :func:`simulate_stellar_convection`.
    KX, KY, K2 : ndarray of float, shape (ny, nx)
        Wavenumber grids from :func:`_spectral_grid_2d`.

    Returns
    -------
    float
        Total kinetic energy :math:`\\sum \\frac{1}{2}(u^2+v^2)`.

    Examples
    --------
    >>> import numpy as np
    >>> _, _, KX, KY, K2 = _spectral_grid_2d(32, 32, 2 * np.pi, 2 * np.pi)
    >>> KE = kinetic_energy(np.zeros((32, 32)), KX, KY, K2)
    >>> KE == 0.0
    True
    """
    psi = _poisson_solve_streamfunction(omega_snapshot, K2)
    u, v = _velocity_from_streamfunction(psi, KX, KY)
    return float(0.5 * np.sum(u**2 + v**2))


