def alpha_omega_growth_rate(alpha: float, shear: float, k, eta: float):
    """Closed-form linear growth rate of the alpha-omega dynamo wave.

    From the dispersion relation :math:`s^2=i\\alpha G k` (see the module
    docstring), the growing branch's real part is
    :math:`\\sigma=\\sqrt{|\\alpha G k|/2}-\\eta k^2` -- positive
    (dynamo action beats Ohmic decay) once :math:`|\\alpha Gk|` is large
    enough relative to :math:`\\eta^2k^4`, i.e. at long enough wavelength
    for fixed diffusivity.

    Parameters
    ----------
    alpha : float
        Alpha-effect coefficient.
    shear : float
        Rotational shear rate :math:`G` (the Omega effect).
    k : float or ndarray
        Wavenumber(s).
    eta : float
        Magnetic diffusivity.

    Returns
    -------
    float or ndarray
        Growth rate :math:`\\sigma`, same shape as `k`.

    See Also
    --------
    alpha_omega_wave_frequency : The companion imaginary part (wave frequency magnitude).
    simulate_alpha_omega_dynamo : Full simulation this closed form is checked against.

    Examples
    --------
    >>> round(alpha_omega_growth_rate(alpha=1.0, shear=5.0, k=1.0, eta=0.05), 4)
    1.5311
    """
    k = np.asarray(k, dtype=float)
    sigma = np.sqrt(np.abs(alpha * shear * k) / 2.0) - eta * k**2
    return sigma if sigma.ndim else float(sigma)


def alpha_omega_wave_frequency(alpha: float, shear: float, k):
    """Closed-form magnitude of the alpha-omega dynamo wave's angular frequency.

    :math:`|\\omega_f| = \\sqrt{|\\alpha Gk|/2}` (see the module docstring
    for the derivation). Only the magnitude is returned; the propagation
    *direction* depends on the sign of :math:`\\alpha Gk` and this
    module's specific stepping convention -- empirically, with
    :func:`simulate_alpha_omega_dynamo`'s time-stepping and the
    :math:`e^{ikx}` Fourier convention used throughout, the wave
    (for ``alpha * shear > 0``, i.e. a positive-``k`` mode with
    :math:`\\alpha Gk>0``) migrates toward **decreasing** :math:`x`, i.e.
    it travels in the ``-x`` direction (verified against the simulation
    in this module's test suite and visible in
    :func:`physicskit.astro.visualizers.plot_dynamo_butterfly_diagram`'s
    diagonal stripes).

    Parameters
    ----------
    alpha : float
        Alpha-effect coefficient.
    shear : float
        Rotational shear rate :math:`G`.
    k : float or ndarray
        Wavenumber(s).

    Returns
    -------
    float or ndarray
        :math:`|\\omega_f|`, same shape as `k`.

    Examples
    --------
    >>> round(alpha_omega_wave_frequency(alpha=1.0, shear=5.0, k=1.0), 4)
    1.5811
    """
    k = np.asarray(k, dtype=float)
    freq = np.sqrt(np.abs(alpha * shear * k) / 2.0)
    return freq if freq.ndim else float(freq)


def simulate_alpha_omega_dynamo(
    A0: NDArray[np.float64],
    B0: NDArray[np.float64],
    alpha: float,
    shear: float,
    eta: float,
    Lx: float,
    dt: float,
    n_steps: int,
    save_every: int = 1,
):
    """Time-step the linear 1D alpha-omega mean-field dynamo equations exactly, per Fourier mode.

    Because :math:`\\partial_t A=\\alpha B+\\eta\\partial_x^2 A`,
    :math:`\\partial_t B=G\\partial_x A+\\eta\\partial_x^2 B` is linear,
    each Fourier mode's amplitude pair :math:`(\\hat A(k,t),\\hat B(k,t))`
    evolves independently under a 2x2 constant-coefficient linear ODE,
    :math:`d/dt\\,(\\hat A,\\hat B)^T = M(k)\\,(\\hat A,\\hat B)^T` with

    .. math::

        M(k) = \\begin{pmatrix}-\\eta k^2 & \\alpha \\\\ iGk & -\\eta k^2\\end{pmatrix},

    so it can be advanced *exactly* over a step `dt` via the matrix
    exponential :math:`\\exp(M(k)\\,dt)`, with no time-discretization error
    whatsoever. Writing :math:`M(k)=-\\eta k^2 I + N(k)` with
    :math:`N(k)=\\begin{pmatrix}0&\\alpha\\\\iGk&0\\end{pmatrix}`, one has
    :math:`N(k)^2 = i\\alpha Gk\\,I`, so with :math:`s_0=\\sqrt{i\\alpha Gk}`
    (principal branch; :math:`s_0=0` at :math:`k=0`),

    .. math::

        \\exp(N(k)\\,dt) = \\cosh(s_0 dt)\\,I + \\frac{\\sinh(s_0 dt)}{s_0}\\,N(k)

    (the usual generalized Euler formula for a matrix whose square is a
    scalar multiple of the identity), and
    :math:`\\exp(M(k)\\,dt) = e^{-\\eta k^2 dt}\\exp(N(k)\\,dt)`. This is
    applied to every Fourier mode at once (vectorized over `k`, not
    looped), then inverse-transformed back to real space.

    Parameters
    ----------
    A0, B0 : ndarray of float, shape (nx,)
        Initial poloidal-flux proxy and toroidal field on a periodic grid
        of ``nx = len(A0)`` points over ``[0, Lx)``.
    alpha : float
        Alpha-effect coefficient.
    shear : float
        Rotational shear rate :math:`G`.
    eta : float
        Magnetic diffusivity.
    Lx : float
        Physical domain size.
    dt : float
        Time step.
    n_steps : int
        Total number of steps.
    save_every : int, default 1
        Save a snapshot every this many steps.

    Returns
    -------
    times : ndarray of float, shape (n_saved,)
    A_snapshots : ndarray of float, shape (n_saved, nx)
    B_snapshots : ndarray of float, shape (n_saved, nx)

    See Also
    --------
    alpha_omega_growth_rate : Closed-form growth rate this stepping is checked against.
    dominant_mode_growth_rate : Extracts the numerically observed growth rate from the output here.

    Examples
    --------
    >>> import numpy as np
    >>> x = np.linspace(0, 2 * np.pi, 32, endpoint=False)
    >>> A0 = 1e-3 * np.cos(x)
    >>> B0 = np.zeros_like(A0)
    >>> times, A_snaps, B_snaps = simulate_alpha_omega_dynamo(A0, B0, alpha=1.0, shear=5.0, eta=0.05, Lx=2 * np.pi, dt=0.01, n_steps=20, save_every=5)
    >>> A_snaps.shape
    (5, 32)
    >>> bool(np.all(np.isfinite(A_snaps)))
    True
    """
    A0 = np.asarray(A0, dtype=float)
    B0 = np.asarray(B0, dtype=float)
    nx = A0.shape[0]
    k = 2.0 * np.pi * np.fft.fftfreq(nx, d=Lx / nx)

    c = 1j * alpha * shear * k
    s0 = np.sqrt(c)
    dt_s0 = s0 * dt
    cosh_term = np.cosh(dt_s0)
    sinh_over_s0 = np.where(s0 == 0, dt, np.divide(np.sinh(dt_s0), s0, out=np.zeros_like(dt_s0), where=(s0 != 0)))
    decay = np.exp(-eta * k**2 * dt)

    A_hat = np.fft.fft(A0)
    B_hat = np.fft.fft(B0)

    times = [0.0]
    A_snapshots = [A0.copy()]
    B_snapshots = [B0.copy()]

    t = 0.0
    for step in range(1, n_steps + 1):
        new_A_hat = decay * (cosh_term * A_hat + sinh_over_s0 * alpha * B_hat)
        new_B_hat = decay * (cosh_term * B_hat + sinh_over_s0 * (1j * k * shear) * A_hat)
        A_hat, B_hat = new_A_hat, new_B_hat
        t += dt
        if step % save_every == 0:
            times.append(t)
            A_snapshots.append(np.real(np.fft.ifft(A_hat)))
            B_snapshots.append(np.real(np.fft.ifft(B_hat)))

    return np.array(times), np.array(A_snapshots), np.array(B_snapshots)


def dominant_mode_growth_rate(A_snapshots: NDArray[np.float64], dt_save: float, window_frac: float = 0.5) -> float:
    """Numerically observed exponential growth rate of the total field energy.

    Fits a line to :math:`\\log\\left(\\sum_x A(x,t)^2\\right)` versus time
    (least squares) and returns half the slope -- since energy
    :math:`\\propto A^2` grows as :math:`e^{2\\sigma t}` for a field
    growing as :math:`e^{\\sigma t}`. Only the *last* `window_frac` of the
    snapshots are used for the fit: an alpha-omega dynamo mode has two
    eigenbranches (:math:`\\sigma\\pm` in the module docstring's
    derivation), and unless the initial condition happens to be a pure
    eigenmode of the faster-growing branch (e.g. `B0` all zero, as in
    this module's typical test setup), the early evolution is a
    transient mix of both branches that will bias a whole-history fit;
    restricting to the late-time window isolates the asymptotically
    dominant branch, which is what :func:`alpha_omega_growth_rate`
    predicts. Used to validate :func:`simulate_alpha_omega_dynamo`
    against that closed form.

    Parameters
    ----------
    A_snapshots : ndarray of float, shape (n_saved, nx)
        Field snapshots, e.g. `A_snapshots` or `B_snapshots` from
        :func:`simulate_alpha_omega_dynamo`.
    dt_save : float
        Time interval between consecutive snapshots.
    window_frac : float, default 0.5
        Fraction of the snapshot history (counted from the end) used for
        the fit.

    Returns
    -------
    float
        The fitted growth rate :math:`\\sigma`.

    Examples
    --------
    >>> import numpy as np
    >>> t = np.arange(10) * 0.1
    >>> sigma_true = 2.0
    >>> A_snaps = np.exp(sigma_true * t)[:, None] * np.ones((10, 4))
    >>> round(dominant_mode_growth_rate(A_snaps, dt_save=0.1), 6)
    2.0
    """
    energy = np.sum(A_snapshots**2, axis=1)
    n = energy.shape[0]
    times = np.arange(n) * dt_save
    start = max(0, n - max(2, int(np.ceil(n * window_frac))))
    log_energy = np.log(energy[start:] + 1e-300)
    slope, _ = np.polyfit(times[start:], log_energy, 1)
    return float(slope / 2.0)
